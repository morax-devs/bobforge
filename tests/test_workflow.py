def test_fixer_provider_error_halts_and_does_not_inflate_patches():
    from backend.model_client import ProviderError, GenerationResult
    buggy_code = "def solve(): return False\n"
    failing_tests = """import unittest
from main import solve
class Tests(unittest.TestCase):
    def test_it(self):
        self.assertTrue(solve())
"""
    provider_err_res = JsonGenerationResult(
        data=None,
        provider="anthropic",
        status="provider_error",
        source="anthropic",
        error=ProviderError(provider="anthropic", message="Anthropic quota error: Credit balance is too low", category="quota_exceeded"),
    )
    raw_provider_err = GenerationResult(
        text="",
        provider="anthropic",
        status="provider_error",
        source="anthropic",
        error=ProviderError(provider="anthropic", message="Anthropic quota error: Credit balance is too low", category="quota_exceeded"),
    )
    with patch("backend.agents.CLIENT.generate_json", return_value=provider_err_res), \
         patch("backend.agents.CLIENT.generate", return_value=raw_provider_err), \
         patch("backend.agents._local_program", return_value=("generic", buggy_code, failing_tests)):
        result = run_workflow("Implement a solver function", max_iterations=3)

    assert result["test_result"]["passed"] is False
    # Stopped at iteration 1 instead of continuing to 3
    assert result["iterations"] == 1
    assert result["repair_blocked"] is True
    assert "Repair stopped:" in result["message"]
    # Check that events do not claim "Applied patch"
    fixer_events = [e for e in result["events"] if e["agent"] == "Fixer"]
    assert len(fixer_events) == 1
    assert "Repair attempt 1 failed:" in fixer_events[0]["message"]
    assert "Applied patch" not in fixer_events[0]["message"]
    # History contains ONLY Builder draft, no fake patch iterations
    assert len(result["history"]) == 1
    assert result["history"][0]["agent"] == "Builder"


