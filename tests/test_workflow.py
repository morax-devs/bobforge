def test_sandbox_telemetry_extraction():
    sample_stderr = """test_one (test_main.Tests.test_one) ... FAIL
test_two (test_main.Tests.test_two) ... ok

======================================================================
FAIL: test_one (test_main.Tests.test_one)
----------------------------------------------------------------------
Traceback (most recent call last):
  File "test_main.py", line 4, in test_one
    self.assertEqual(1, 2)
AssertionError: 1 != 2

----------------------------------------------------------------------
Ran 2 tests in 0.001s

FAILED (failures=1)
"""
    telemetry = parse_unittest_telemetry("", sample_stderr)
    assert telemetry["total_count"] == 2
    assert telemetry["passed_count"] == 1
    assert telemetry["failing_tests"] == ["test_one"]
    assert "AssertionError: 1 != 2" in telemetry["assertion_error"]


